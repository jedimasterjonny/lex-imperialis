#!/usr/bin/env python3
"""Project each fleet play's `vars:` block into the fleet scenario's fixtures.

The composed-fleet scenario converges the real roles against the real per-host
variables, so the fixture must be what the play says and nothing else. Hand
transcription would make it a second source of truth that drifts silently, and a
fixture that disagrees with the play means the converge is testing a host that
does not exist. So the fixture is generated and a pre-commit hook regenerates it,
failing the commit when the committed copy has drifted.

The vault stands in as hand-written `inventory/group_vars/all.yml`, which Ansible
resolves *underneath* these files by its own precedence — inventory group_vars for
a named group outrank inventory group_vars for `all` — so a play var always wins
without this script merging anything.

roles/fleet/README.md has the rest.
"""

import pathlib
import sys

import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
SCENARIO = REPO / "roles/fleet/molecule/default"
GROUP_VARS = SCENARIO / "inventory/group_vars"
CONVERGE = SCENARIO / "converge.yml"

# The plays the harness converges. Extend alongside the instance that runs the
# shape — a fixture with no instance behind it is ungoverned by construction.
PLAYS = ["solar", "rogue-trader"]

# Roles the converge drops because there is nothing to compose — they stand alone
# and their own scenarios cover them. Only what the input plays actually contain:
# a role appearing in a play but neither excluded nor converged fails check_roles
# loudly, so this list needs no anticipation.
EXCLUDED_ROLES = {"common", "sshd", "firewalld", "nfs"}

HEADER = """\
# Generated by bin/gen-fixture-hostvars.py from playbooks/{play}.yml — do not edit.
# Regenerate with `python3 bin/gen-fixture-hostvars.py`; the pre-commit hook fails
# on drift. Vault secrets stand in from all.yml, which Ansible resolves beneath this.
"""


class FixtureDumper(yaml.SafeDumper):
    """yamllint --strict runs tree-wide, and its indent-sequences rule rejects a
    block sequence flush with its key — which is what PyYAML emits by default."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def group_name(play):
    """Ansible rejects `-` in a group name, so the group is the inventory key
    with hyphens folded to underscores."""
    return play["hosts"].replace("-", "_")


def render(name, play):
    body = yaml.dump(
        play.get("vars", {}),
        Dumper=FixtureDumper,
        sort_keys=False,
        default_flow_style=False,
        width=140,
    )
    return group_name(play), HEADER.format(play=name) + "---\n" + body


# Play keys this harness does not model. The fixture projects `vars:` and
# check_roles holds `roles:`, so anything that runs tasks or loads further vars is
# content the converge silently would not have. Keys like become: or gather_facts:
# are inert here and must not veto an edit to a production play.
UNMODELLED_PLAY_KEYS = {"vars_files", "pre_tasks", "post_tasks", "tasks", "handlers"}


def check_play_keys(name, doc):
    """A fleet playbook is one play. check_roles reads every play in converge.yml,
    but the source side projects doc[0] — so a second play would slip past silently,
    taking its roles and vars with it."""
    if len(doc) != 1:
        return [f"playbooks/{name}.yml holds {len(doc)} plays; the fixture projects only the first"]
    unmodelled = set(doc[0]) & UNMODELLED_PLAY_KEYS
    if not unmodelled:
        return []
    return [f"playbooks/{name}.yml carries play keys the harness does not model: {sorted(unmodelled)}"]


def check_roles(plays):
    """The fixture is generated so it can never drift from the play. The converge's
    `roles:` list is just as load-bearing — it is what decides handler resolution
    order and which roles meet each other at all — and it is the one part still
    hand-written. Hold it to the same contract: the converge must run exactly the play's roles, in the play's order,
    minus the declared exclusions."""
    converge = {
        play["hosts"]: play.get("roles", [])
        for play in yaml.safe_load(CONVERGE.read_text(encoding="utf-8"))
    }
    problems = []
    for name, play in plays:
        want = [r for r in play.get("roles", []) if r not in EXCLUDED_ROLES]
        got = converge.get(group_name(play), [])
        if got != want:
            problems.append(
                f"converge role list has drifted from playbooks/{name}.yml:"
                f"\n    play: {want}\n    converge: {got}"
            )
    return problems


def main():
    GROUP_VARS.mkdir(parents=True, exist_ok=True)
    docs = [
        (name, yaml.safe_load((REPO / "playbooks" / f"{name}.yml").read_text(encoding="utf-8")))
        for name in PLAYS
    ]
    problems = [p for name, doc in docs for p in check_play_keys(name, doc)]
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1

    plays = [(name, doc[0]) for name, doc in docs]
    for name, play in plays:
        group, content = render(name, play)
        (GROUP_VARS / f"{group}.yml").write_text(content, encoding="utf-8")

    problems = check_roles(plays)
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
