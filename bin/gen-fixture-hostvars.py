#!/usr/bin/env python3
"""Project each fleet host's variables into the fleet scenario's fixtures.

A host's variables are `inventory/host_vars/<host>.yml` and nothing else. A play may
carry none in any form: every way it could outranks inventory and reaches that one
play, invisible to the rest of the fleet.

roles/fleet/README.md has the rest.
"""

import pathlib
import sys

import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
HOST_VARS = REPO / "inventory/host_vars"
HOSTS = REPO / "inventory/hosts.yml"
PLAYBOOKS = REPO / "playbooks"
SCENARIO = REPO / "roles/fleet/molecule/default"
GROUP_VARS = SCENARIO / "inventory/group_vars"
CONVERGE = SCENARIO / "converge.yml"

# The plays the harness converges. Extend alongside the instance that runs the
# shape — a fixture with no instance behind it is ungoverned by construction.
PLAYS = ["solar", "rogue-trader"]

# Everything a fleet play may hold. An allowlist rather than a ban on the keys that can
# carry a variable, because that list is open-ended — `vars:`, `vars_files:`,
# `environment:` and `module_defaults:` all do, and so will the next keyword Ansible
# adds. Every one of them outranks inventory and reaches a single play.
PLAY_KEYS = {
    "name",
    "hosts",
    "become",
    "gather_facts",
    "roles",
    "ansible.builtin.import_playbook",
}

# Roles the converge drops because there is nothing to compose — they stand alone
# and their own scenarios cover them. Only what the input plays actually contain:
# a role appearing in a play but neither excluded nor converged fails check_roles
# loudly, so this list needs no anticipation.
EXCLUDED_ROLES = {"common", "sshd", "firewalld", "nfs"}

HEADER = """\
# Generated by bin/gen-fixture-hostvars.py from inventory/host_vars/{host}.yml.
# Do not edit — regenerate with `python3 bin/gen-fixture-hostvars.py`; the pre-commit
# hook fails on drift. Vault secrets stand in from all.yml, resolved beneath this.
"""


class FixtureDumper(yaml.SafeDumper):
    """yamllint --strict runs tree-wide, and its indent-sequences rule rejects a
    block sequence flush with its key — which is what PyYAML emits by default."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def load_yaml(path):
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def group_name(play):
    """Ansible rejects `-` in a group name, so the group is the inventory key
    with hyphens folded to underscores."""
    return play["hosts"].replace("-", "_")


def check_sidecar_vars():
    """A `host_vars`/`group_vars` directory beside the plays outranks inventory — rank 10
    against 9 — so it re-forms the split silently, and it is the mistake this layout
    invites."""
    return [
        f"playbooks/{name}/ outranks inventory/ and the fixture cannot see it"
        for name in ("host_vars", "group_vars")
        if (PLAYBOOKS / name).exists()
    ]


def check_play(name, play):
    """Role params — a `roles:` entry that is a mapping rather than a bare name — rank
    higher than anything else here short of extra vars."""
    problems = [
        f"playbooks/{name} declares {key}; a fleet play holds only {sorted(PLAY_KEYS)} "
        "— a variable belongs in inventory/host_vars/, and the fixture models nothing else"
        for key in sorted(set(play) - PLAY_KEYS)
    ]
    if any(not isinstance(role, str) for role in play.get("roles") or []):
        problems.append(f"playbooks/{name} passes role params, which outrank inventory")
    return problems


def check_inventory(targeted):
    """One host_vars file per inventory host. A spelling Ansible reads and this does not
    (`solar.yaml`) leaves the fixture modelling an empty host; one it never reads
    (`scholam.yml` — that play's host is `this_host`) is inert on the fleet with nothing
    to say so; and a file that is missing, empty or wholly commented leaves the host with
    no variables at all, now that plays carry none — `touch` is the obvious wrong answer
    to the missing-file message. A play's `hosts:` is only a claim: a typo matches
    nothing, warns, and still exits 0, so gitops_reconcile reports a clean apply over an
    unmanaged host."""

    def walk(group):
        found = set(group.get("hosts") or {})
        for child in (group.get("children") or {}).values():
            found |= walk(child or {})
        return found

    hosts = walk(load_yaml(HOSTS)["all"])
    want = {f"{host}.yml" for host in hosts}
    found = {path.name for path in HOST_VARS.iterdir()} if HOST_VARS.is_dir() else set()
    problems = []
    if stray := sorted(found - want):
        problems.append(
            f"inventory/host_vars/ holds exactly one <host>.yml per host; rename or "
            f"remove: {stray}"
        )
    if missing := sorted(want - found):
        problems.append(f"inventory/host_vars/ has no file for: {missing}")
    if empty := sorted(name for name in found & want if not load_yaml(HOST_VARS / name)):
        problems.append(f"inventory/host_vars/ declares nothing for: {empty}")
    if unknown := sorted(targeted - hosts):
        problems.append(f"a play targets what inventory/hosts.yml does not define: {unknown}")
    return problems


def check_single_play(name, doc):
    """check_roles reads every play in converge.yml, but the fixture projects doc[0] — so
    a second play here would slip past silently, taking its roles with it."""
    if len(doc) == 1:
        return []
    return [f"playbooks/{name}.yml holds {len(doc)} plays; the fixture projects only the first"]


def check_roles(plays):
    """The fixture is generated so it can never drift from its source. The converge's
    `roles:` list is just as load-bearing — it is what decides handler resolution
    order and which roles meet each other at all — and it is the one part still
    hand-written. Hold it to the same contract: the converge must run exactly the
    play's roles, in the play's order, minus the declared exclusions."""
    converge = {play["hosts"]: play.get("roles", []) for play in load_yaml(CONVERGE)}
    problems = []
    for name, play in plays:
        want = [r for r in play.get("roles", []) if r not in EXCLUDED_ROLES]
        got = converge.get(group_name(play), [])
        if got != want:
            problems.append(
                f"converge role list has drifted from playbooks/{name}.yml:"
                f"\n    play: {want}\n    converge: {got}"
            )
    return problems


def render(host):
    """Keyed on the inventory host, never the play file: playbooks/scholam.yml targets
    this_host, and host_vars is what Ansible reads."""
    body = yaml.dump(
        load_yaml(HOST_VARS / f"{host}.yml"),
        Dumper=FixtureDumper,
        sort_keys=False,
        default_flow_style=False,
        width=140,
    )
    return HEADER.format(host=host) + "---\n" + body


def report(problems):
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


def main():
    GROUP_VARS.mkdir(parents=True, exist_ok=True)
    # Every playbook, site.yml included: an `import_playbook` entry takes play keys too,
    # and site.yml is the one gitops_reconcile applies. Derived from disk, so a new play
    # cannot join the fleet and skip the checks.
    docs = {
        path.name: load_yaml(path) or []
        for path in sorted(PLAYBOOKS.glob("*.yml")) + sorted(PLAYBOOKS.glob("*.yaml"))
    }
    entries = [(name, play) for name, doc in docs.items() for play in doc]

    problems = check_sidecar_vars()
    problems += [p for name, play in entries for p in check_play(name, play)]
    # site.yml's import_playbook entries carry no hosts:.
    problems += check_inventory({play["hosts"] for _, play in entries if "hosts" in play})
    problems += [
        f"PLAYS names playbooks/{name}.yml, which does not exist"
        for name in PLAYS
        if f"{name}.yml" not in docs
    ]
    problems += [
        p
        for name in PLAYS
        if f"{name}.yml" in docs
        for p in check_single_play(name, docs[f"{name}.yml"])
    ]
    if problems:
        return report(problems)

    plays = [(name, docs[f"{name}.yml"][0]) for name in PLAYS]
    for _, play in plays:
        path = GROUP_VARS / f"{group_name(play)}.yml"
        path.write_text(render(play["hosts"]), encoding="utf-8")

    return report(check_roles(plays))


if __name__ == "__main__":
    sys.exit(main())
